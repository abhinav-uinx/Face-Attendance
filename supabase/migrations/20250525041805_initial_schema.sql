insert into storage.buckets (id, name, public)
values
  ('admin', 'admin', true),
  ('attendance', 'attendance', true),
  ('tutor', 'tutor', true)
on conflict (id) do update
set name = excluded.name,
    public = excluded.public;

drop policy if exists "admin bucket public read" on storage.objects;
drop policy if exists "admin bucket authenticated write" on storage.objects;
drop policy if exists "attendance bucket public read" on storage.objects;
drop policy if exists "attendance bucket authenticated write" on storage.objects;
drop policy if exists "tutor bucket public read" on storage.objects;
drop policy if exists "tutor bucket authenticated write" on storage.objects;

create policy "admin bucket public read" on storage.objects
  for select using (bucket_id = 'admin');

create policy "admin bucket authenticated write" on storage.objects
  for all to authenticated
  using (bucket_id = 'admin')
  with check (bucket_id = 'admin');

create policy "attendance bucket public read" on storage.objects
  for select using (bucket_id = 'attendance');

create policy "attendance bucket authenticated write" on storage.objects
  for all to authenticated
  using (bucket_id = 'attendance')
  with check (bucket_id = 'attendance');

create policy "tutor bucket public read" on storage.objects
  for select using (bucket_id = 'tutor');

create policy "tutor bucket authenticated write" on storage.objects
  for all to authenticated
  using (bucket_id = 'tutor')
  with check (bucket_id = 'tutor');

